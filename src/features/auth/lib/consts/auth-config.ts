/** Маршрут экрана входа. Один на всё приложение — гварду и редиректам нужен общий. */
export const LOGIN_ROUTE = '/login'

/**
 * Маршрут обязательной смены пароля. Отдельный экран, а не диалог поверх приложения: пока
 * пароль не сменён, сервер отвечает 403 на всё остальное (ТЗ §А5), и показывать за диалогом
 * пустые экраны с ошибками незачем.
 */
export const CHANGE_PASSWORD_ROUTE = '/change-password'

/**
 * Параметр строки запроса, в котором гвард запоминает, куда человек шёл до редиректа на
 * вход. После успешного входа его возвращают туда же, а не на главную.
 */
export const REDIRECT_PARAM = 'from'

/**
 * Требовать вход для защищённых маршрутов. <b>По умолчанию выключено.</b>
 *
 * Флаг зеркалит серверный `webbuh.auth.enabled`, и выключен он по той же причине: хеши
 * паролей из 1С непереносимы, после миграции пароль не задан ни у кого, поэтому
 * включённая проверка закрыла бы приложение для всех разом — включая дев-стенды. Порядок
 * такой: администратор выдаёт первые пароли → поднимают флаг на бэкенде → поднимают этот.
 *
 * Пока флаг снят, экран входа доступен по прямой ссылке и полностью работоспособен:
 * токены выдаются и подставляются в запросы, просто никто ни на что не выгоняется.
 *
 * <b>Флаги двух сторон обязаны включаться вместе.</b> Только фронт — приложение гоняет на
 * вход при живом бэкенде без проверки (безобидно, но бессмысленно). Только бэкенд — все
 * запросы отвечают 401, а увести пользователя на вход некому.
 */
export const AUTH_ENABLED = import.meta.env.VITE_AUTH_ENABLED === 'true'
