import type { TokenPair } from '@/shared/types/auth.types'

/**
 * Контракт входа по лицу (ADR-0069 §D11 в репозитории webbuh).
 *
 * Типы описывают ровно то, что отдаёт и принимает сервер — не «удобную для фронта» модель.
 * Причина жёсткая: сервер измеряет физику отражения света от лица, и любое расхождение между
 * тем, что он назначил, и тем, что нарисовал браузер, он увидит как низкую корреляцию и откажет
 * во входе. Поэтому расписание здесь не пересобирается и не «оптимизируется» — оно исполняется.
 */

/** Один сегмент светового расписания: чем залить экран и на сколько. */
export interface FlashSegment {
  /** Порядковый номер сегмента. Уходит обратно в `meta.frames[].seg` — по нему сервер сопоставляет кадр с цветом. */
  i: number
  /** Цвет заливки в формате `#RRGGBB`. Назначается сервером случайно: угадать расписание заранее — и есть атака. */
  rgb: string
  /** Длительность сегмента в миллисекундах. Кратна кадру обновления экрана (16,7 мс при 60 Гц). */
  ms: number
}

/** Параметры съёмки. Приходят с каждым челленджем и у каждого свои — константами не зашивать. */
export interface CaptureParams {
  width: number
  height: number
  /** Качество JPEG для `canvas.toBlob`. */
  jpegQuality: number
  targetFps: number
  /**
   * Границы числа кадров. Вычислены сервером ПОД КОНКРЕТНОЕ расписание этого челленджа —
   * прислать меньше или больше значит получить отказ `TOO_FEW_FRAMES` / `TOO_MANY_FRAMES`.
   */
  minFrames: number
  maxFrames: number
  /** Сколько последних кадров прогрева попадает в отправку (нужны серверу как базовая линия). */
  baselineFrames: number
}

/** Ответ `POST /api/auth/face/challenge`. */
export interface FaceChallengeResponse {
  challengeId: string
  expiresInSeconds: number
  /** Длительность нейтрального прогрева до начала цветных сегментов. */
  warmupMs: number
  /** Цвет прогрева. */
  warmupRgb: string
  /** Четыре цветных сегмента плюс закрывающий нейтральный. */
  schedule: FlashSegment[]
  capture: CaptureParams
}

/** Метаданные одного снятого кадра. Уходят на сервер в `meta.frames`. */
export interface FrameMeta {
  /** Номер кадра. Определяет порядок частей в multipart — порядок значим. */
  n: number
  /** Время кадра от начала съёмки, мс. Берётся из `requestVideoFrameCallback`, а не из момента обработки. */
  tMs: number
  /** Индекс сегмента расписания; `-1` — кадр прогрева. */
  seg: number
}

/**
 * Возможности камеры — только ЧТЕНИЕ (§D11).
 *
 * Экспозицию и баланс белого мы не трогаем: в Firefox и Safari их нет вовсе, в Chrome они
 * работают не на всех камерах, а применённые настройки могут пережить сессию и помешать другим
 * сайтам. Но калибровке нужно знать, на каком железе снималось, поэтому прочитанное отправляем.
 */
export interface CaptureCapabilities {
  supported?: Record<string, boolean>
  track?: Record<string, unknown>
}

/** Тело части `meta` в multipart-запросе `POST /api/auth/face/verify`. */
export interface VerifyMeta {
  frames: FrameMeta[]
  capabilities: CaptureCapabilities
  screen: {
    w: number
    h: number
    dpr: number
  }
}

/** Снятый кадр: метаданные плюс закодированный JPEG. */
export interface CapturedFrame {
  meta: FrameMeta
  blob: Blob
}

/**
 * Причины отказа по качеству материала (HTTP 422) — фиксированный перечень §D11.
 *
 * Только по ним клиент показывает подсказку «что сделать иначе». Всё остальное — обезличенный
 * отказ: живость и несовпадение личности сервер намеренно не различает в ответе, чтобы подбор
 * не получал обратной связи.
 */
export type FaceQualityReason =
  | 'NO_FACE'
  | 'MULTIPLE_FACES'
  | 'FACE_TOO_SMALL'
  | 'FACE_TOO_LARGE'
  | 'FACE_MOVED'
  | 'LOW_FRAME_RATE'
  | 'LOW_SIGNAL'
  | 'TOO_FEW_FRAMES'
  | 'TOO_MANY_FRAMES'

/** Исход попытки входа по лицу — то, на что реагирует UI. */
export type FaceVerifyOutcome =
  /**
   * Успех несёт токены: сервер отвечает тем же `TokenPairDto`, что и обычный вход.
   *
   * Сохраняет сессию НЕ эта фича, а форма входа — у неё уже есть доступ к хранилищу
   * аутентификации. Слайс входа по лицу знает только про съёмку и проверку; знай он ещё и про
   * то, как в приложении заводится сессия, его нельзя было бы переиспользовать нигде, кроме
   * экрана логина (например, для повторного подтверждения личности перед платёжкой).
   */
  | { kind: 'success'; tokens: TokenPair }
  /** 401 — обезличенный отказ. Причину не показываем, потому что сервер её и не сообщает. */
  | { kind: 'rejected' }
  /** 422 — материал негодный, попытку можно повторить осмысленно. */
  | { kind: 'quality'; reason: FaceQualityReason }
  /** 429 — исчерпан лимит попыток. */
  | { kind: 'rateLimited' }
  /** 503 — контур выключен, перегружен или движок недоступен. Попытка НЕ израсходована (§D3.1). */
  | { kind: 'unavailable' }
  /** Сеть, отмена, отказ в доступе к камере — всё, что случилось на нашей стороне. */
  | { kind: 'clientError'; detail: string }
