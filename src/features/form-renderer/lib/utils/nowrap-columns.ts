import type { DocumentAttribute } from '@/entities/document-type'

/**
 * Колонка ТЧ, которой перенос текста НЕ нужен.
 *
 * <p>Значения ячейки ТЧ переносятся по ширине колонки (`whitespace-normal
 * break-words` в `table-cell-renderer.tsx`) — иначе длинное значение
 * обрезается многоточием. У колонок ниже это правило даёт обратный эффект:
 * значения длинные по своей природе (ФИО, наименование должности, «Целевые
 * текущие трансферты из областного бюджета…»), и перенос раздувает КАЖДУЮ
 * строку ТЧ. В эталоне 1С они идут в одну строку с многоточием.
 *
 * <p>Состав списка — шапка ТЧ «Начисления» документа «Начисление зарплаты
 * сотрудникам» в эталоне 1С; те же колонки с теми же именами есть в ТЧ других
 * документов и справочников.
 *
 * <p>Опознание по 1С-имени с фолбэком на `code` — тот же приём, что у
 * канонических колонок пересчёта строки (`row-sum-recalc.ts`): `code1C`
 * стабилен, а `code` у части типов приезжает транслитерацией. Совпадение по
 * НАЧАЛУ имени: `Отработано` — это `ОтработаноДней`/`ОтработаноЧасов`,
 * `Подразделение` — `ПодразделениеОрганизации`, «Источник финансирования» в ТЧ
 * движений бухрегистра — `ИсточникФинансированияДт`/`Кт`.
 *
 * <p>Правило-близнец SDUI-мира — `features/sdui/lib/utils/nowrap-columns.ts`.
 * Намеренно КОПИЯ, а не общий модуль: прямые импорты между легаси и SDUI
 * запрещены, а ключ у колонки в этих мирах разный (здесь 1С-имя атрибута, там
 * binding ноды).
 */
const NOWRAP_NAMES_1C = [
  'ИсточникФинансирования',
  'Сотрудник',
  'ПериодРегистрации',
  'Подразделение',
  'Должность',
  'ВидНачисления',
  'ПлановыйОклад',
  'ГрафикРаботы',
  'НормаДней',
  'НормаЧасов',
  'Отработано',
  'НачалоПериода',
  'ОкончаниеПериода',
  'НормативнаяНагрузка',
  'НедельнаяНагрузка',
  'Размер',
]

/** Те же имена в транслитерации бэка — на типах, приезжающих без `code1C`. */
const NOWRAP_CODES = [
  'istochnikfinansirovaniya',
  'sotrudnik',
  'periodregistratsii',
  'podrazdelenie',
  'dolzhnost',
  'vidnachisleniya',
  'planovyyoklad',
  'grafikraboty',
  'normadney',
  'normachasov',
  'otrabotano',
  'nachaloperioda',
  'okonchanieperioda',
  'normativnayanagruzka',
  'nedelnayanagruzka',
  'razmer',
]

export function isNoWrapColumn(column: DocumentAttribute): boolean {
  const code = column.code.toLowerCase()
  return (
    NOWRAP_NAMES_1C.some((name) => column.code1C.startsWith(name)) ||
    NOWRAP_CODES.some((prefix) => code.startsWith(prefix))
  )
}
