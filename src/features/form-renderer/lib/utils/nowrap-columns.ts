import type { DocumentAttribute } from '@/entities/document-type'

/**
 * Колонка ТЧ, которой перенос текста НЕ нужен.
 *
 * <p>Значения ячейки ТЧ переносятся по ширине колонки (`whitespace-normal
 * break-words` в `table-cell-renderer.tsx`) — иначе длинное значение
 * обрезается многоточием. У «Источника финансирования» это правило даёт
 * обратный эффект: наименования источников длинные («Целевые текущие
 * трансферты из областного бюджета…»), и перенос раздувает КАЖДУЮ строку ТЧ на
 * три-четыре текстовых строки. Значение здесь опознают по началу, поэтому
 * колонка держится в одну строку с многоточием.
 *
 * <p>Опознание по 1С-имени с фолбэком на `code` — тот же приём, что у
 * канонических колонок пересчёта строки (`row-sum-recalc.ts`): `code1C`
 * стабилен, а `code` у части типов приезжает транслитерацией.
 *
 * <p>Совпадение по НАЧАЛУ имени: тот же реквизит встречается как
 * `ИсточникФинансированияДт`/`Кт` (ТЧ движений бухрегистра) и
 * `ИсточникФинансированияНаРазделение` (ТЧ разделений по шаблонам).
 *
 * <p>Правило-близнец SDUI-мира — `features/sdui/lib/utils/nowrap-columns.ts`.
 * Намеренно КОПИЯ, а не общий модуль: прямые импорты между легаси и SDUI
 * запрещены, а ключ у колонки в этих мирах разный (здесь 1С-имя атрибута, там
 * binding ноды).
 */
export function isNoWrapColumn(column: DocumentAttribute): boolean {
  return (
    column.code1C.startsWith('ИсточникФинансирования') ||
    /^istochnikfinansirovaniya/i.test(column.code)
  )
}
