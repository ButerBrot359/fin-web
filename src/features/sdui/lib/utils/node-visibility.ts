import type { ViewNode } from '../../types/view'

/**
 * Единое правило видимости узла для рендерера: `props.visible === false`
 * скрывает узел любого типа — контейнер (VSTACK/HSTACK/GROUP/GRID), кнопку,
 * ссылку, подпись. Отсутствие пропа означает «видим».
 *
 * Правило одинаково работает для стартового значения из дерева `POST /api/view`
 * и для рантайм-патча `setProp(nodeId, "visible", false)` — патч кладёт значение
 * в те же `node.props`, из которых читает эта функция.
 *
 * Применяется в `NodeRenderer` — единственной точке, через которую проходят все
 * рисуемые узлы, поэтому скрытый контейнер не рендерит ни себя (рамку, заголовок,
 * gap), ни поддерево. Поля дополнительно гасят себя сами через `useFieldNode`
 * (там строгое `=== true`), это не конфликтует: оба условия только скрывают.
 *
 * Колонки таблиц через `NodeRenderer` не проходят и живут по своему правилу —
 * см. `column-visibility.ts`.
 */
export function isNodeVisible(node: ViewNode): boolean {
  return node.props?.visible !== false
}
