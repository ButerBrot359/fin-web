/**
 * Колонки ТЧ, в которых перенос текста ОТКЛЮЧЁН.
 *
 * <p>По умолчанию ячейка ТЧ переносит длинное значение по ширине колонки
 * (`readonlyCellTextStyle` и multiline-редакторы в `table-cell-editor.tsx`) —
 * иначе оно вылезает поверх соседней колонки. У колонок ниже это правило даёт
 * обратный эффект: значения длинные по своей природе («Целевые текущие
 * трансферты из областного бюджета…», «ГЛАВНЫЙ ЭКОНОМИСТ ОТДЕЛА ПЛАНИРОВАНИЯ И
 * БЮДЖЕТА»), и перенос раздувает КАЖДУЮ строку ТЧ на три-четыре текстовых
 * строки. Значение здесь опознают по началу, поэтому колонки держатся в одну
 * строку с многоточием.
 *
 * <p>Правило по БИНДИНГУ, а не по подписи колонки: подпись бэк может менять и
 * локализовать, биндинг — имя реквизита 1С («Объект.Начисления.
 * ИсточникФинансирования») и одинаков во всех ТЧ документа (Начисления,
 * Перерасчет, ОПВ, ВОСМС, ИПН) — одна запись покрывает их все.
 *
 * <p>Список на фронте — временная мера: как только бэк начнёт присылать признак
 * переноса в props колонки, проверка переедет туда, а список уйдёт.
 */
const NOWRAP_BINDINGS = new Set([
  // Объект.<ТЧ>.ИсточникФинансирования
  'istochnikfinansirovaniya',
  // Объект.<ТЧ>.Сотрудник — ФИО целиком в одну строку не влезает никогда
  'sotrudnik',
  // Объект.Начисления.Должность / Объект.Перерасчет.Должность
  'dolzhnost',
  // Объект.<ТЧ>.ПодразделениеОрганизации; короткое `Podrazdelenie` — та же
  // колонка в ТЧ других документов (движения, регистры)
  'podrazdelenieorganizatsii',
  'podrazdelenie',
  // Объект.Начисления.ВидНачисления
  'vidnachisleniya',
])

/** true — колонке с таким биндингом перенос текста не нужен. */
export function isNoWrapBinding(binding: string): boolean {
  return NOWRAP_BINDINGS.has(binding.toLowerCase())
}
