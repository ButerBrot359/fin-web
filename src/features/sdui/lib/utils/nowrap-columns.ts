/**
 * Колонки ТЧ, в которых перенос текста ОТКЛЮЧЁН.
 *
 * <p>По умолчанию ячейка ТЧ переносит длинное значение по ширине колонки
 * (`readonlyCellTextStyle` и multiline-редакторы в `table-cell-editor.tsx`) —
 * иначе оно вылезает поверх соседней колонки. Для «Источника финансирования»
 * это правило даёт обратный эффект: наименования источников длинные
 * («Целевые текущие трансферты из областного бюджета…»), и перенос раздувает
 * КАЖДУЮ строку ТЧ на три-четыре текстовых строки. Значение здесь опознают по
 * началу, поэтому колонка держится в одну строку с многоточием.
 *
 * <p>Правило по БИНДИНГУ, а не по подписи колонки: подпись бэк может менять и
 * локализовать, биндинг — имя реквизита 1С («Объект.Начисления.
 * ИсточникФинансирования») и одинаков во ВСЕХ ТЧ всех документов, где эта
 * колонка есть: Начисления, Перерасчет, ОПВ, ОППВ, ОПВР, ОСМС, ВОСМС, ИПН, СН,
 * СО, Удержания, ЗарплатаКВыплате, ТМЗ, ОсновныеСредства, Расходы… — одна
 * запись покрывает их все.
 *
 * <p>Совпадение по НАЧАЛУ биндинга: тот же реквизит приезжает под именами
 * `ИсточникФинансированияДт`/`Кт` (ТЧ движений бухрегистра) и
 * `ИсточникФинансированияНаРазделение` (ТЧ разделений по шаблонам). Это одна и
 * та же колонка с теми же длинными наименованиями, и правило для них общее.
 *
 * <p>Список на фронте — временная мера: как только бэк начнёт присылать признак
 * переноса в props колонки, проверка переедет туда, а список уйдёт.
 */
const NOWRAP_BINDING_PREFIXES = ['istochnikfinansirovaniya']

/** true — колонке с таким биндингом перенос текста не нужен. */
export function isNoWrapBinding(binding: string): boolean {
  const normalized = binding.toLowerCase()
  return NOWRAP_BINDING_PREFIXES.some((prefix) => normalized.startsWith(prefix))
}
