import type { TableRow } from '../hooks/use-table-sync'

/**
 * Служебные ключи строки ТЧ — вычисленное бэком состояние строки, а не её
 * данные. Приходят внутри объекта строки, рядом с `rowId`.
 *
 * Класс ключей уже существовал (`__rowParentIds` — SCRUM-332 §3,
 * `__subkontoAllowedTypes`); условное оформление добавило к нему ещё три.
 * Общее у всех: колонкой не показываются, ячейкой не редактируются и обратно
 * на сервер не уезжают — бэк считает их сам на каждом OPEN и EVENT.
 */
export const SERVICE_ROW_KEYS = {
  /** Коды колонок, обязательных именно в этой строке. */
  requiredCells: '__requiredCells',
  /** Коды колонок, недоступных для ввода в этой строке. */
  readonlyCells: '__readonlyCells',
  /** Строка недоступна целиком. */
  rowReadonly: '__rowReadonly',
} as const

/**
 * Префикс служебного ключа. Проверка идёт по префиксу, а не по списку выше:
 * ключи этого класса заводятся на бэке по мере переноса правил из 1С, и
 * забытый в списке новый ключ уехал бы обратно как «значение ячейки».
 */
const SERVICE_ROW_KEY_PREFIX = '__'

/**
 * Строка без служебных ключей — для всего, что уезжает на сервер или копируется
 * в новую строку.
 *
 * Зачем на отправке: бэк считает состояние строки сам (на save неизвестные коды
 * отбрасываются), поэтому эхо служебных ключей — лишний трафик в каждом EVENT'е
 * по ТЧ.
 *
 * Зачем на копировании: «Скопировать» переносит ЗНАЧЕНИЯ строки. Состояние
 * посчитано для строки-источника, и без этой очистки копия строки, целиком
 * заблокированной по `__rowReadonly`, приезжала бы заблокированной ещё до
 * ответа сервера — с чужим, уже неверным состоянием.
 */
export function omitServiceRowKeys(row: TableRow): TableRow {
  const result: TableRow = { rowId: row.rowId }
  for (const [key, value] of Object.entries(row)) {
    if (key.startsWith(SERVICE_ROW_KEY_PREFIX)) continue
    result[key] = value
  }
  return result
}
