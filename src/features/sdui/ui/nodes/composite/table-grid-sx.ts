import type { SxProps, Theme } from '@mui/material'

/**
 * Цвет линий сетки таблицы. Литерал, а не токен темы MUI: он обязан совпадать с
 * `border-ui-03` — классом Tailwind, которым `verticalSubRows`
 * (`lib/utils/build-column-defs.ts`) рисует разделитель под-строк вертикальной
 * группы. Тот разделитель — часть той же сетки, и дефолтный
 * `theme.palette.divider` (rgba(0,0,0,0.12)) заметно от него отличается:
 * горизонтальные линии внутри колонки были бы одного цвета, а вертикальные
 * между колонками — другого.
 *
 * Значение — `colors.ui['03']` из `tailwind.config.ts`.
 */
const GRID_LINE_COLOR = '#c3cee0'

/**
 * Сетка табличной части «как в 1С»: внешняя рамка, вертикальная линия между
 * колонками и горизонтальные между строками.
 *
 * <p>Зачем: MUI из коробки рисует только `border-bottom` у `TableCell`, то есть
 * горизонтальные линии. Без вертикальных двухрядная шапка читается как сплошное
 * поле текста — какая подпись к какой колонке относится, видно только по
 * положению. В 1С колонки разделены линиями на всю высоту шапки, и именно это
 * делает пары «Вид начисления / Способ расчёта» однозначными.
 *
 * <p>Реализовано дескендант-селекторами на `<Table>`, а не через
 * `styleOverrides` темы: тема задела бы ВСЕ таблицы обоих миров (легаси-списки,
 * отчёты, пикеры), а сетка нужна табличным частям документа.
 *
 * <p>`borderRight` снимается у последней ячейки строки — иначе линия удвоилась
 * бы с внешней рамкой. `:last-child`, а не `:last-of-type`: у ячеек шапки с
 * `colSpan` соседями по строке могут быть разные элементы.
 *
 * <p>Тип — `satisfies`, а не аннотация `: SxProps<Theme>`. `SxProps` — ОБЪЕДИНЕНИЕ
 * (объект | функция от темы | массив), и спред такого значения в другой объектный
 * литерал TypeScript распределяет по всем членам объединения, включая массивный:
 * результат тащит `length`/`concat`/`join` и обратно в `sx` уже не присваивается.
 * `satisfies` проверяет форму, но оставляет тип объектным литералом — спред
 * остаётся корректным.
 */
export const TABLE_GRID_SX = {
  border: `1px solid ${GRID_LINE_COLOR}`,
  '& .MuiTableCell-root': {
    borderRight: `1px solid ${GRID_LINE_COLOR}`,
    borderBottomColor: GRID_LINE_COLOR,
  },
  '& .MuiTableCell-root:last-child': {
    borderRight: 0,
  },
} satisfies SxProps<Theme>
