/**
 * Порядок наложения оверлеев.
 *
 * ЗАЧЕМ. У MUI разные типы оверлеев сидят на разных слоях: `Dialog` — на
 * `zIndex.modal` (1300), `Drawer` — на `zIndex.drawer` (1200). Пока панель была
 * одна, это не мешало. Со вложенными панелями порядок слоёв перестал совпадать
 * с порядком открытия: панель выбора (drawer) открывалась ИЗ окна строки
 * (полноэкранный dialog) и уезжала ПОД него — пользователь нажимал «Показать
 * все», и «ничего не происходило», хотя панель была смонтирована.
 *
 * Правило: слой определяется позицией в стеке, а не типом компонента. Что
 * открыто позже — то и выше.
 */

/** Базовый слой стека панелей — уровень модалок MUI (`theme.zIndex.modal`). */
export const OVERLAY_Z_BASE = 1300

/** Шаг между соседними панелями стека. */
export const OVERLAY_Z_STEP = 10

/**
 * Слой легаси-панели выбора справочника (`dict-sidebar`). Она живёт вне стека
 * SDUI-панелей, но всегда открывается ПОВЕРХ текущего — в том числе из
 * SDUI-панели, поэтому стоит выше любой из них.
 *
 * Ниже тостов (`zIndex.snackbar` = 1400): сообщение об ошибке должно быть видно
 * поверх всего, включая открытую панель.
 */
export const DICT_SIDEBAR_Z = 1380

/** Слой i-й панели стека (0 — самая нижняя). */
export function panelZIndex(index: number): number {
  return OVERLAY_Z_BASE + index * OVERLAY_Z_STEP
}

/**
 * Слой всплывающих списков MUI (`Popper`/`Popover`: выпадашка `Autocomplete`,
 * меню, календарь пикера даты).
 *
 * ЗАЧЕМ. У MUI этот слой прибит к `theme.zIndex.modal` (1300) — то есть НИЖЕ
 * панелей стека (1310 и выше) и легаси-панели выбора справочника
 * (DICT_SIDEBAR_Z). Выпадающий список поля, которое лежит ВНУТРИ такой панели,
 * рисовался под её же фоном: запрос вариантов уходил, ответ приходил, а
 * пользователь видел «поле не даёт вариантов для выбора».
 *
 * Popper всегда принадлежит полю САМОГО ВЕРХНЕГО оверлея (в нижних нет фокуса,
 * а открытие нового оверлея закрывает список), поэтому единый слой выше всех
 * панелей корректен. Ниже тостов (`zIndex.snackbar` = 1400) — сообщение об
 * ошибке должно быть видно поверх всего.
 */
export const POPUP_Z = 1390
