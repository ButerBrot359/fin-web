import { toIsoDate, toIsoDateTime } from '@/shared/lib/utils/iso-date'

/**
 * Сериализация значения дата-инпута для отправки на сервер (SCRUM-265 FE-6).
 *
 * Обе ветки отдают ЛОКАЛЬНОЕ время, как его набрал пользователь: сервер, по
 * своей политике, offset у строки отрезает, а не конвертирует. `toISOString()`
 * же переводит время в UTC, и в зоне восточнее Гринвича на провод уходило
 * ЧУЖОЕ значение: «30.08 00:00 (+05:00)» → «2026-08-29T19:00:00.000Z», сервер
 * сохранял 29.08 19:00 — ровно это и видел пользователь после записи.
 *
 * `dateOnly` (DATE-поля): голая календарная дата `yyyy-MM-dd`.
 * datetime-поля: `yyyy-MM-ddTHH:mm:ss` — без зоны и без миллисекунд.
 * `format` работает в локальной зоне, поэтому сдвига нет по построению.
 *
 * Двузначный год достраивается до века (SCRUM-279 D6) — здесь, потому что это
 * единственная воронка «Date из пикера → строка на провод»: и шапка формы, и
 * ячейка табличной части ведут себя одинаково по построению, а не по совпадению.
 * Значение возвращается в пикер уже расширенным (`value`-prop → `parseISO`), так
 * что пользователь видит достроенный год, а не только сервер.
 */
export function serializeDateInput(
  value: Date | null,
  dateOnly?: boolean
): string {
  return (dateOnly ? toIsoDate(value) : toIsoDateTime(value)) ?? ''
}
